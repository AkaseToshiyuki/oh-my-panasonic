import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
const source=await readFile(new URL('../extension/statusbar-format.js',import.meta.url),'utf8');
const {selection,cpuSample,cpuPercent,memoryPercent,powerValues,batteryValues,render}=await import('data:text/javascript;base64,'+Buffer.from(source).toString('base64'));
assert.deepEqual(selection(null),['battery']);
assert.deepEqual(selection([]),[]);
assert.deepEqual(selection(['cpu','cpu','bad','battery','remaining','cpu_power','memory','temperature']),['cpu','battery','remaining','cpu_power','memory']);
assert.ok(Math.abs(cpuPercent(cpuSample('cpu 100 0 100 800 0 0 0 0 50 0'),cpuSample('cpu 110 0 110 880 0 0 0 0 60 0'))-20)<1e-9);
assert.equal(cpuPercent(null,cpuSample('cpu 1 0 0 9')),null);
assert.equal(cpuPercent({total:100,idle:50},{total:10,idle:5}),null);
assert.equal(cpuSample('cpu nan 0 0 0'),null);
assert.equal(memoryPercent('MemTotal: 1000 kB\nMemAvailable: 750 kB'),25);
assert.equal(memoryPercent('MemTotal: 1000 kB'),null);
const power={timestamp:100,sample:{received:50,watts:0,platform_w:12,temperature:40}};
assert.deepEqual(powerValues(power,101,51),{cpu_power:0,platform_power:12,temperature:40});
for(const [now,mono] of [[113,51],[101,59],[101,49],[97,51]])assert.deepEqual(powerValues(power,now,mono),{});
const battery={IsPresent:true,State:2,EnergyRate:10,Energy:30,Percentage:85,TimeToEmpty:0};
const data=batteryValues(k=>battery[k]);
assert.equal(data.remaining,10800);
assert.equal(render(['battery','remaining','battery_power','cpu','cpu_power'],{...data,cpu:20,cpu_power:0}),'85% · 剩余 3h · 放电 10.0W · CPU 20% · CPU 0.0W');
battery.State=1;
assert.equal(render(['remaining','battery_power'],batteryValues(k=>battery[k])),'充电 10.0W');
assert.equal(render(['cpu','battery','memory','temperature','platform_power'],{cpu:NaN,battery:101,memory:-1,temperature:151,platform_power:Infinity}),'');
assert.equal(render([],data),'');
console.log('Statusbar formatting, stale readings and selection checks passed');
