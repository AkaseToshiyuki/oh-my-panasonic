import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
const source=await readFile(new URL('../extension/statusbar-format.js',import.meta.url),'utf8');
const {selection,cpuSample,cpuPercent,memoryPercent,powerValues,batteryValues,render}=await import('data:text/javascript;base64,'+Buffer.from(source).toString('base64'));
assert.deepEqual(selection(null),['battery']);
assert.deepEqual(selection([]),[]);
assert.deepEqual(selection(['cpu','cpu','bad','battery','remaining','cpu_power','memory','temperature']),['cpu','battery','remaining','cpu_power','memory']);
assert.ok(Math.abs(cpuPercent(cpuSample('cpu 100 0 100 800 0 0 0 0 50 0'),cpuSample('cpu 110 0 110 880 0 0 0 0 60 0'))-20)<1e-9);
assert.equal(cpuPercent(null,cpuSample('cpu 1 0 0 9')),null);
assert.equal(cpuPercent({total:100,idle:50},{total:10,idle:5}),null);
assert.equal(cpuSample('cpu nan 0 0 0'),null);
assert.equal(memoryPercent('MemTotal: 1000 kB\nMemAvailable: 750 kB'),25);
assert.equal(memoryPercent('MemTotal: 1000 kB'),null);
const power={timestamp:100,sample:{received:50,watts:0,platform_w:12,temperature:40}};
assert.deepEqual(powerValues(power,101,51),{cpu_power:0,platform_power:12,temperature:40});
for(const [now,mono] of [[113,51],[101,59],[101,49],[97,51]])assert.deepEqual(powerValues(power,now,mono),{});
const battery={IsPresent:true,State:2,EnergyRate:10,Energy:30,Percentage:85,TimeToEmpty:0};
const data=batteryValues(k=>battery[k]);
assert.equal(data.remaining,10800);
assert.equal(render(['battery','remaining','battery_power','cpu','cpu_power'],{...data,cpu:20,cpu_power:0}),'85% · 剩余 3h · 放电 10.0W · CPU 20.0% · CPU 0.0W');
battery.State=1;
assert.equal(render(['remaining','battery_power'],batteryValues(k=>battery[k])),'充电 10.0W');
assert.equal(render(['cpu','battery','memory','temperature','platform_power'],{cpu:NaN,battery:101,memory:-1,temperature:151,platform_power:Infinity}),'');
assert.equal(render([],data),'');
assert.equal(render(['remaining'],{energy:30,platform_power:10,discharging:false}),'约 3h');
assert.equal(render(['remaining'],{energy:30,cpu_power:2,discharging:false}),'');
assert.equal(render(['cpu'],{cpu:.3}),'CPU 0.3%');
console.log('Statusbar formatting, stale readings and selection checks passed');
const touch=await readFile(new URL('../extension/touchpad-state.js',import.meta.url),'utf8');
const {parseState,pulseKind,position,visiblePoints}=await import('data:text/javascript;base64,'+Buffer.from(touch).toString('base64'));
const frame={points:[[30,50],[70,50]],scroll:-1,click:1,tap:0,fingers:2,seq:1};
assert.deepEqual(parseState(JSON.stringify(frame)),frame);
assert.equal(pulseKind(frame,true,'fingers'),2);
assert.equal(pulseKind(frame,true,'areas'),1);
assert.equal(pulseKind({...frame,click:0,tap:2},false,'fingers'),0);
for(const invalid of [{...frame,scroll:3},{...frame,points:[[NaN,2]]},{...frame,seq:-1},{...frame,points:[[1,2],[3,4],[5,6]]}])
    assert.throws(()=>parseState(JSON.stringify(invalid)));
assert.ok(Math.hypot(...position([100,100],10))<=6.61);
const triple={...frame,multi:{points:[[20,60],[50,20],[80,60]],fingers:3,click:1,tap:0}};
const parsed=parseState(JSON.stringify(triple));
assert.equal(parsed.points.length,3);
assert.equal(pulseKind(parsed,true,'fingers'),3);
assert.equal(pulseKind(parsed,true,'areas'),1);
assert.deepEqual(visiblePoints(parsed),triple.multi.points);
for(const points of [[[20,50],[80,50]],[[40,50],[50,50],[60,50]]]) {
    const shown=visiblePoints({...parsed,points});
    assert.equal(shown.length,3);
    assert.ok(shown.every((p,i)=>shown.slice(i+1).every(q=>Math.hypot(p[0]-q[0],p[1]-q[1])>=25)));
}
assert.equal(pulseKind({...parsed,tap:3},false,'fingers'),0);
assert.equal(pulseKind({...parsed,tap:3},true,'fingers'),3);
assert.deepEqual(visiblePoints({...parsed,points:[]}),[]);
for(const multi of [null,{}, {...triple.multi,fingers:4}, {...triple.multi,points:[[0,-1]]}, {...triple.multi,click:'3'}])
    assert.throws(()=>parseState(JSON.stringify({...frame,multi})));
console.log('Touchpad frame validation and gesture rendering checks passed');
